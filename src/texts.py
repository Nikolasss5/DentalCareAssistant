def appointment_text(language, appointment):
    language = normalize_language(language)
    status = str(appointment.get("status", "")).strip().lower()

    status_uk = {
        "confirmed": "Підтверджено клінікою",
        "confirmed_by_patient": "Підтверджено пацієнтом",
        "reschedule_requested": "Запит на перенесення",
    }
    status_ru = {
        "confirmed": "Подтверждено клиникой",
        "confirmed_by_patient": "Подтверждено пациентом",
        "reschedule_requested": "Запрос на перенос",
    }

    if language == "ru":
        return (
            "📋 <b>Ваша запись</b>\n\n"
            f"Имя: <b>{appointment.get('patient_name', '')}</b>\n"
            f"Услуга: {appointment.get('procedure_type', '')}\n"
            f"Дата: <b>{appointment.get('appointment_date', '')}</b>\n"
            f"Время: <b>{appointment.get('appointment_time', '')}</b>\n"
            f"Статус: {status_ru.get(status, status or '—')}\n\n"
            "Для переноса или отмены свяжитесь с администратором."
        )

    return (
        "📋 <b>Ваш запис</b>\n\n"
        f"Ім’я: <b>{appointment.get('patient_name', '')}</b>\n"
        f"Послуга: {appointment.get('procedure_type', '')}\n"
        f"Дата: <b>{appointment.get('appointment_date', '')}</b>\n"
        f"Час: <b>{appointment.get('appointment_time', '')}</b>\n"
        f"Статус: {status_uk.get(status, status or '—')}\n\n"
        "Для перенесення або скасування зв’яжіться з адміністратором."
    )


